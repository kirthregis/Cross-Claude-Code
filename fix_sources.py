lines.append('  const text = (title + " " + body).toLowerCase();')
lines.append('  const hasDj = text.includes("dj") || text.includes("disc jockey") || text.includes("deejay");')
lines.append('  const hasBooking = ["booking", "looking for", "need a", "wanted", "hiring", "hire", "residency", "resident", "gig", "performer", "entertainment"].some(k => text.includes(k));')
