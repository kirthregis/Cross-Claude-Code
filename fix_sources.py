lines.append('    const items = text.split(/<item>|<entry>/).slice(1);')
lines.append('    const leads: RawLead[] = [];')
lines.append('    for (const item of items.slice(0, 30)) {')
lines.append('      const pick = (tag: string) =>')
lines.append('        item.match(new RegExp(`<${tag}[^>]*>([\\\\s\\\\S]*?)<\\\\/${tag}>`))?.[1]')
lines.append('          ?.replace(/<!\[CDATA\[|\]\]>/g, "")')
lines.append('          ?.replace(/<[^>]+>/g, "")')
lines.append('          ?.trim();')
lines.append('      const title = pick("title") ?? "";')
lines.append('      const body = pick("description") ?? pick("summary") ?? pick("content") ?? "";')
lines.append('      const link = pick("link") ?? "";')
lines.append('      const pubDate = pick("pubDate") ?? pick("published") ?? "";')
lines.append('      if (!isRelevant(title, body)) continue;')
lines.append('      leads.push({')
lines.append('        sourceKind: kind,')
lines.append('        sourceName: name,')
lines.append('        sourceUrl: link || undefined,')
lines.append('        title: title || `Listing from ${name}`,')
lines.append('        body: title + " " + body,')
lines.append('        postedAt: pubDate ? new Date(pubDate).toISOString() : new Date().toISOString(),')
lines.append('      });')
lines.append('    }')
lines.append('    return leads;')
lines.append('  } catch {')
lines.append('    return [];')
lines.append('  }')
lines.append('}')
