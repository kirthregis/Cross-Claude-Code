# -*- coding: utf-8 -*-
import subprocess

lines = []
lines.append('const STATIC = "emy-v10";')
lines.append('const DYN = "emy-dyn-v10";')
lines.append('const SHELL = "/studio";')
lines.append('const PRE = ["/studio","/studio/gigradar","/studio/analytics","/studio/distribute","/studio/community","/studio/epk","/manifest.json","/icon-192.png","/icon-512.png"];')
lines.append('')
lines.append('self.addEventListener("install", e => {')
lines.append('  self.skipWaiting();')
lines.append('  e.waitUntil(caches.open(STATIC).then(c => Promise.allSettled(PRE.map(u => c.add(u).catch(() => null)))));')
lines.append('});')
lines.append('')
lines.append('self.addEventListener("activate", e => {')
lines.append('  e.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(k => k !== STATIC && k !== DYN).map(k => caches.delete(k)))).then(() => self.clients.claim()));')
lines.append('});')
lines.append('')
lines.append('self.addEventListener("fetch", e => {')
lines.append('  const req = e.request;')
lines.append('  if (req.method !== "GET") return;')
lines.append('  const url = new URL(req.url);')
lines.append('  if (url.origin !== self.location.origin) return;')
lines.append('  if (url.protocol === "chrome-extension:") return;')
lines.append('')
lines.append('  // API routes: always network, never cache, never clone')
lines.append('  if (url.pathname.startsWith("/api/")) {')
lines.append('    e.respondWith(')
lines.append('      fetch(req).catch(() => new Response(JSON.stringify({error:"offline"}), {')
lines.append('        status: 503,')
lines.append('        headers: {"Content-Type": "application/json"}')
lines.append('      }))')
lines.append('    );')
lines.append('    return;')
lines.append('  }')
lines.append('')
lines.append('  // Navigation: network first, fallback to cache, fallback to shell')
lines.append('  if (req.mode === "navigate") {')
lines.append('    e.respondWith(')
lines.append('      fetch(req).then(res => {')
lines.append('        if (res.ok) {')
lines.append('          const clone = res.clone();')
lines.append('          caches.open(DYN).then(c => c.put(req, clone));')
lines.append('        }')
lines.append('        return res;')
lines.append('      }).catch(async () => {')
lines.append('        const cached = await caches.match(req);')
lines.append('        if (cached) return cached;')
lines.append('        const shell = await caches.match(SHELL);')
lines.append('        return shell ?? new Response("Offline", {status:503});')
lines.append('      })')
lines.append('    );')
lines.append('    return;')
lines.append('  }')
lines.append('')
lines.append('  // Static assets: cache first, background revalidate')
lines.append('  e.respondWith(')
lines.append('    caches.match(req).then(cached => {')
lines.append('      const net = fetch(req).then(res => {')
lines.append('        if (res.ok) {')
lines.append('          const clone = res.clone();')
lines.append('          caches.open(DYN).then(c => c.put(req, clone));')
lines.append('        }')
lines.append('        return res;')
lines.append('      }).catch(() => cached ?? new Response("", {status:408}));')
lines.append('      return cached ?? net;')
lines.append('    })')
lines.append('  );')
lines.append('});')
lines.append('')
lines.append('self.addEventListener("message", e => {')
lines.append('  if (e.data?.type === "SKIP_WAITING") self.skipWaiting();')
lines.append('});')
lines.append('')
lines.append('self.addEventListener("push", e => {')
lines.append('  const d = e.data ? e.data.json() : {title:"EMY Studio",body:"New update"};')
lines.append('  e.waitUntil(self.registration.showNotification(d.title, {body:d.body,icon:"/icon-192.png"}));')
lines.append('});')

with open("public/sw.js", "w", encoding="utf-8") as f:
    f.write("\n".join(lines))

size = __import__("os").path.getsize("public/sw.js")
print(f"WROTE public/sw.js ({size} bytes)")

# Verify API routes are never cached
with open("public/sw.js", "r", encoding="utf-8") as f:
    c = f.read()

checks = ["/api/", "never cache", "clone = res.clone()", "STATIC", "DYN", "skipWaiting", "navigate"]
missing = [x for x in checks if x not in c]
if missing:
    print("MISSING:", missing)
else:
    print(f"AUDIT OK - {len(checks)} checks passed")
    subprocess.run(["git", "add", "public/sw.js"], check=True)
    r = subprocess.run(["git", "status", "--short"], capture_output=True, text=True)
    print(r.stdout)
    subprocess.run(["git", "commit", "-m", "Fix SW v10: API routes never cached, response clone error fixed"], check=True)
    subprocess.run(["git", "push", "origin", "main"], check=True)
    print("DONE")
