# -*- coding: utf-8 -*-
import subprocess, os

lines = []
lines.append('import { nanoid } from "nanoid";')
lines.append('import { ALL_SOURCES } from "./sources";')
lines.append('import { normalise } from "./extract";')
lines.append('import { scoreGig } from "./score";')
lines.append('import { alert, sendMorningDigest, isDigestTime } from "./notify";')
lines.append('import { alreadyAlerted, logAlert, recordSweep } from "./db";')
lines.append('import type { Gig, RawLead } from "./types";')
lines.append('import { registerProfileLoader } from "./profile-store";')
lines.append('')
lines.append('registerProfileLoader();')
lines.append('')
lines.append('const DJ_SIGNALS = [')
lines.append('  "dj", "disc jockey", "deejay", "booking", "book a dj",')
lines.append('  "looking for a dj", "need a dj", "dj wanted", "dj required",')
lines.append('  "dj needed", "hiring dj", "dj hire", "resident dj", "dj residency",')
lines.append('  "dj set", "dj slot", "dj night", "dj gig", "dj opportunity",')
lines.append('  "dj booking", "dj performance", "dj entertainment", "afro house",')
lines.append('  "house dj", "techno dj", "electronic music dj",')
lines.append('];')
lines.append('')
lines.append('function isDjLead(lead: RawLead): boolean {')
lines.append('  const text = (lead.title + " " + lead.body).toLowerCase();')
lines.append('  return DJ_SIGNALS.some(s => text.includes(s));')
lines.append('}')
lines.append('')
lines.append('export interface SweepResult {')
lines.append('  found: number;')
lines.append('  newGigs: number;')
lines.append('  alerted: number;')
lines.append('  digested?: number;')
lines.append('  errors: string[];')
lines.append('  sources: { id: string; found: number; errors: string[] }[];')
lines.append('  gigs: Gig[];')
lines.append('}')
lines.append('')
lines.append('export async function processLeads(leads: RawLead[]): Promise<SweepResult> {')
lines.append('  const errors: string[] = [];')
lines.append('  const fresh: Gig[] = [];')
lines.append('  for (const lead of leads) {')
lines.append('    try {')
lines.append('      if (!isDjLead(lead)) continue;')
lines.append('      const base = normalise(lead);')
lines.append('      const s = scoreGig(base);')
lines.append('      if (s.tier === "suppress") continue;')
lines.append('      const gig: Gig = { ...base, id: nanoid(10), score: s.score, stage: "new" };')
lines.append('      fresh.push(gig);')
lines.append('    } catch (e) {')
lines.append('      errors.push(`normalise failed for "${lead.title}": ${e}`);')
lines.append('    }')
lines.append('  }')
lines.append('  let alerted = 0;')
lines.append('  for (const g of fresh) {')
lines.append('    if (alreadyAlerted(g.id)) continue;')
lines.append('    const s = scoreGig(g);')
lines.append('    try {')
lines.append('      const r = await alert(g, s);')
lines.append('      logAlert(g.id);')
lines.append('      if (r.sent.length) alerted++;')
lines.append('    } catch (e) {')
lines.append('      errors.push(`alert failed for ${g.id}: ${e}`);')
lines.append('    }')
lines.append('  }')
lines.append('  return { found: leads.length, newGigs: fresh.length, alerted, errors, sources: [], gigs: fresh };')
lines.append('}')
lines.append('')
lines.append('export async function sweep(): Promise<SweepResult> {')
lines.append('  const errors: string[] = [];')
lines.append('  const leads: RawLead[] = [];')
lines.append('  const sourceStats: SweepResult["sources"] = [];')
lines.append('  const results = await Promise.allSettled(')
lines.append('    ALL_SOURCES.filter(s => s.configured()).map(async s => {')
lines.append('      const sourceLeads = await s.fetch();')
lines.append('      return { id: s.id, leads: sourceLeads, errors: [] as string[] };')
lines.append('    })')
lines.append('  );')
lines.append('  for (const r of results) {')
lines.append('    if (r.status === "fulfilled") {')
lines.append('      leads.push(...r.value.leads);')
lines.append('      sourceStats.push({ id: r.value.id, found: r.value.leads.length, errors: [] });')
lines.append('    } else {')
lines.append('      errors.push(String(r.reason));')
lines.append('    }')
lines.append('  }')
lines.append('  const out = await processLeads(leads);')
lines.append('  out.errors.push(...errors);')
lines.append('  out.sources = sourceStats;')
lines.append('  if (isDigestTime()) {')
lines.append('    try {')
lines.append('      const d = await sendMorningDigest();')
lines.append('      if (d.sent) out.digested = d.count;')
lines.append('    } catch (e) {')
lines.append('      out.errors.push(`digest failed: ${e}`);')
lines.append('    }')
lines.append('  }')
lines.append('  recordSweep(out.found, out.newGigs, out.errors);')
lines.append('  return out;')
lines.append('}')

with open("src/lib/ingest.ts", "w", encoding="utf-8") as f:
    f.write("\n".join(lines))

size = os.path.getsize("src/lib/ingest.ts")
print(f"WROTE src/lib/ingest.ts ({size} bytes)")

with open("src/lib/ingest.ts", "r", encoding="utf-8") as f:
    c = f.read()

